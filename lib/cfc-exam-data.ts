export interface BookletQuestion extends QuestionData {
  bookletNumber: number;
  originalTipo4Id: number;
}

export function getBookletQuestions(bookletType: BookletType): BookletQuestion[] {
  const order = BOOKLET_QUESTION_ORDER[bookletType] || BOOKLET_QUESTION_ORDER.tipo4;
  const questionMap = new Map<number, QuestionData>();
  CFC_EXAM_QUESTIONS.forEach((q) => questionMap.set(q.id, q));

  return order.map((originalId, index) => {
    const originalQ = questionMap.get(originalId)!;
    return {
      ...originalQ,
      bookletNumber: index + 1,
      originalTipo4Id: originalId,
    };
  });
}

